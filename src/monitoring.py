"""credit-risk-lab: MONITORING.md generator.

A model that is not monitored is a model on its way to being wrong
quietly. This module generates MONITORING.md at the repo root from the
current results: the score PSI and per-feature CSI state, the
calibration test state, the retraining triggers stated as rules, and
the cadence a real model risk management team would run.

The customary PSI zones (below 0.10 stable, 0.10 to 0.25 investigate,
above 0.25 material shift) are reported as signals, with the caveat
from Yurdakul and Naranjo (2020): those thresholds are rules of thumb
without a Type I/II error basis. A trigger here means "a human looks",
never "the model is fine" or "the model is dead" on its own.
"""
import json
from pathlib import Path

import credit_risk_lab as pipe

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "MONITORING.md"


def _zone(v: float) -> str:
    if v < 0.10:
        return "below 0.10 (customary stable zone)"
    if v < 0.25:
        return "0.10-0.25 (customary investigate zone)"
    return "above 0.25 (customary material-shift zone)"


def write_md() -> str:
    results = json.loads((ROOT / "results" / "results.json").read_text())
    val = results["validation"]
    champ = results["champion"]
    lines = [
        "# credit-risk-lab: monitoring state and plan",
        "",
        "Generated by `src/monitoring.py` from `results/results.json`. "
        "Every value below is from the current pipeline run; the "
        "triggers and cadence are the standing plan a model risk team "
        "would apply to a model of this class.",
        "",
        "## Current state (development sample, train vs test)",
        "",
        f"- Champion: {champ}. Score PSI (train vs test): "
        f"**{val['score_psi_train_vs_test']:.4f}**, "
        f"{_zone(val['score_psi_train_vs_test'])}.",
    ]
    if "auc_ci95" in val:
        ci = val["auc_ci95"]["champion_gradient_boosting"]
        lines.append(
            f"- Champion test AUC: "
            f"{results['models'][champ]['auc']:.4f} with bootstrap 95% "
            f"CI [{ci['lo95']:.4f}, {ci['hi95']:.4f}] "
            f"(results/rigor.json). A future vintage whose AUC falls "
            "below the lower bound is a retraining conversation, not a "
            "rounding error.")
    hl = val.get("hosmer_lemeshow", {})
    if hl:
        h = hl[champ]
        lines.append(
            f"- Hosmer-Lemeshow calibration test, champion: statistic "
            f"{h['statistic']:.3f}, p = {h['p_value']:.4f}. At 9,000 test "
            "accounts this test rejects on minor miscalibration; it is "
            "tracked as a flag to inspect the calibration table, not as "
            "a pass/fail gate (see VALIDATION.md).")
    csi = val.get("csi_per_feature", {})
    if csi:
        worst = sorted(csi.items(), key=lambda kv: -kv[1])[:5]
        lines += ["", "Largest per-feature CSI values right now:", ""]
        for feat, v in worst:
            lines.append(f"- {feat}: {v:.4f} ({_zone(v)})")
    lines += [
        "",
        "Because the development split is random, train-vs-test "
        "stability verifies the machinery only. Production monitoring "
        "compares each new vintage against the development sample and "
        "against the previous vintage; that is where drift would show.",
        "",
        "## Retraining and escalation triggers (rules)",
        "",
        "1. Score PSI against the development sample above 0.25 on any "
        "monthly vintage: freeze automated use, open a review.",
        "2. Score PSI between 0.10 and 0.25, or any core behavioural "
        "feature's CSI above 0.25: investigate within the cycle; check "
        "for data pipeline changes before touching the model.",
        "3. Realized default rate in any score decile outside the "
        "calibration table's observed range by more than 5 percentage "
        "points for two consecutive vintages: recalibration review.",
        "4. Test-style AUC on a fresh labelled vintage below the lower "
        "bound of the development bootstrap CI: full revalidation.",
        "5. Approval-rate gap between any two audited demographic "
        "groups widening by more than 5 percentage points at a fixed "
        "cut-off: fairness review before the next deployment decision.",
        "6. Any change to features, target definition, or portfolio "
        "mix: revalidation regardless of metric state (a change is a "
        "new model for governance purposes).",
        "",
        "## Cadence",
        "",
        "- Monthly: score PSI, per-feature CSI, decile calibration "
        "against realized outcomes, staging migration summary (from "
        "`data/credit.db` queries in `sql/queries.sql`).",
        "- Quarterly: outcomes analysis (AUC, KS, Brier), fairness "
        "audit at the production cut-off, scenario ECL refresh.",
        "- Annually, and on any trigger above: full revalidation in "
        "the VALIDATION.md structure, with the scorecard grade "
        "recomputed and every deduction named.",
        "",
        "## The caveat that governs all of the above",
        "",
        "PSI and CSI thresholds are conventions, not statistics with "
        "error guarantees (Yurdakul and Naranjo, 2020, Journal of Risk "
        "Model Validation). They allocate human attention. The numbers "
        "beside them, the calibration table, and the outcomes analysis "
        "are the evidence; the zones are only the alarm wiring.",
        "",
    ]
    text = "\n".join(lines)
    OUT_MD.write_text(text)
    return text


def main() -> str:
    return write_md()


if __name__ == "__main__":
    write_md()
    print("MONITORING.md written")
